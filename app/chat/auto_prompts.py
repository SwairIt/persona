def detect_overlay(question: str) -> str:
    """Вернуть накладку-инструкцию под тип задачи или '' если не распознано."""
    q = (question or "").lower()
    if not q.strip():
        return ""
    for _name, triggers, overlay in _LIBRARY:
        if any(t in q for t in triggers):
            return "\n\n[Авто-режим под задачу] " + overlay
    return ""


def detected_name(question: str) -> str:
    """Имя распознанного типа задачи (для логов/отладки) или ''."""
    q = (question or "").lower()
    for name, triggers, _overlay in _LIBRARY:
        if any(t in q for t in triggers):
            return name
    return ""
