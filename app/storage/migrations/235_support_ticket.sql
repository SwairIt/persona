-- Поддержка: «любой может написать владельцу, и это до него дойдёт».
--
-- ЗАЧЕМ. До этой миграции обратной связи не было ВООБЩЕ: ни формы, ни ящика.
-- Единственный канал — почта владельца, которую он нигде не публикует, и
-- Telegram, куда пускают не всех. Публичная регистрация открыта (v2.33.1),
-- значит на инстансе уже есть посторонние люди, которым некуда написать.
--
-- ГЛАВНОЕ ОГРАНИЧЕНИЕ, ПОД КОТОРОЕ СПРОЕКТИРОВАНА СХЕМА: почта на этом
-- инстансе НЕ РАБОТАЕТ. kv ``smtp_enabled='true'``, но ``smtp_host`` и
-- ``smtp_from`` пустые → ``app.smtp_delivery.delivery_status()`` отвечает
-- ``'misconfigured'``. Поэтому письмо — это ЗЕРКАЛО, а не канал доставки:
-- источник истины — строка в этой таблице, видимая владельцу на сайте.
-- Отсюда колонки ``owner_notify_status`` / ``owner_notified_at``: обращение
-- обязано ЧЕСТНО помнить, что письма не было, иначе владелец решит, что его
-- уведомили, и будет ждать.
--
-- ── support_ticket ─────────────────────────────────────────────────────────
--
-- РЕШЕНИЯ ПО СХЕМЕ (читать перед правками):
--
-- 1. ``user_id`` NULLABLE + ``ON DELETE SET NULL``. Писать может аноним из
--    интернета — у него нет строки в ``users``, и требовать её значило бы
--    закрыть форму ровно от тех, кому она нужнее всего (человек не может
--    войти → пишет в поддержку). ``SET NULL``, а не ``CASCADE``: если автор
--    удалил аккаунт, его обращение и ответ владельца остаются как история
--    переписки инстанса. Персональные данные при этом не осиротеют — см. п.3.
--
-- 2. CHECK ``user_id IS NOT NULL OR email <> ''``. Обратный адрес обязателен
--    ровно тогда, когда иначе ответить НЕКУДА. У залогиненного адрес известен
--    из ``users``, у анонима — только тот, что он вписал сам. Это инвариант
--    БД, а не проверка формы: любой будущий путь записи (импорт, API, CLI)
--    физически не сможет создать обращение, на которое нельзя ответить.
--
-- 3. ``email`` хранится ОТКРЫТЫМ ТЕКСТОМ и это осознанно: весь смысл поля —
--    чтобы владелец мог написать человеку ответ. Хэш ответить не позволяет.
--    Для залогиненного поле дублирует ``users.email`` НАМЕРЕННО: адрес мог
--    смениться после обращения, а отвечать надо на тот, с которого написали.
--
-- 4. Контекст (``app_version``, ``role``, ``browser_class``, ``source_page``)
--    — КРУПНОЗЕРНИСТЫЙ. Сырой User-Agent НЕ хранится: это классический
--    идентификатор для фингерпринтинга, а для разбора жалобы достаточно
--    «Chrome, мобильный». ``source_page`` — путь БЕЗ query string (в query
--    ходят токены и поисковые запросы).
--
-- 5. ``ip_hash`` — ``sha256(instance_salt || ip)``, первые 16 hex-символов;
--    сырого IP и его подсети тут нет. ЗАЧЕМ вообще: единственный вопрос,
--    ради которого он нужен, — «эти двадцать обращений пришли от одного
--    источника или от двадцати людей?». На это отвечает равенство хэшей, и
--    больше ни для чего он не используется: по нему не блокируют (блокирует
--    in-process rate-limit по живому IP) и его не показывают в UI целиком.
--    Соль инстансная (kv ``support_ip_salt``, генерируется один раз) —
--    без неё 32-битное пространство IPv4 перебирается за секунды, и «хэш»
--    был бы просто длинной записью самого адреса.
--
-- 6. ``status`` — ЧЕТЫРЕ значения в CHECK, а не свободный текст: владелец
--    фильтрует по ним ящик, и опечатка в коде не должна порождать статус,
--    который потом не попадает ни в один фильтр.

CREATE TABLE IF NOT EXISTS support_ticket (
    id                  INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id             INTEGER REFERENCES users(id) ON DELETE SET NULL,
    email               TEXT    NOT NULL DEFAULT '',
    subject             TEXT    NOT NULL,
    body                TEXT    NOT NULL,
    status              TEXT    NOT NULL DEFAULT 'new',
    source_page         TEXT    NOT NULL DEFAULT '',
    app_version         TEXT    NOT NULL DEFAULT '',
    role                TEXT    NOT NULL DEFAULT 'anon',
    browser_class       TEXT    NOT NULL DEFAULT '',
    ip_hash             TEXT    NOT NULL DEFAULT '',
    owner_notify_status TEXT    NOT NULL DEFAULT 'pending',
    owner_notified_at   TEXT,
    created_at          TEXT    NOT NULL DEFAULT (datetime('now')),
    updated_at          TEXT    NOT NULL DEFAULT (datetime('now')),
    CHECK (status IN ('new', 'read', 'answered', 'closed')),
    CHECK (role IN ('anon', 'member', 'owner')),
    -- Ответить должно быть КУДА: либо известен аккаунт, либо оставлен адрес.
    CHECK (user_id IS NOT NULL OR TRIM(email) <> '')
);

-- Горячий запрос ящика: «сначала новые, с фильтром по статусу».
CREATE INDEX IF NOT EXISTS idx_support_ticket_status
    ON support_ticket(status, id DESC);

-- Бейдж «непрочитанных N» и лента без фильтра.
CREATE INDEX IF NOT EXISTS idx_support_ticket_created
    ON support_ticket(created_at DESC);

-- «Все обращения этого аккаунта» — при разборе жалобы и при удалении данных.
CREATE INDEX IF NOT EXISTS idx_support_ticket_user
    ON support_ticket(user_id, id DESC);

-- ── support_message ────────────────────────────────────────────────────────
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА ``last_reply``.
-- Владелец отвечает не один раз: «понял, смотрю» → через день «починил».
-- Одна колонка означала бы, что второй ответ СТИРАЕТ первый, а вместе с ним
-- и запись о том, ушло ли то письмо. Терять переписку в системе, смысл
-- которой — не терять обращения, недопустимо, а таблица стоит трёх строк SQL.
--
-- ПОЧЕМУ ЭТО НЕ ПОЛНОЦЕННЫЙ ТРЕД. Двусторонняя ветка требует, чтобы АНОНИМ
-- мог вернуться и ответить, а это отдельная инфраструктура: одноразовая
-- ссылка-токен в письме, её срок жизни, отзыв, защита от перебора — и всё
-- это поверх почты, которая на инстансе НЕ РАБОТАЕТ. Токен, который некому
-- отправить, не канал связи, а лишняя уязвимая ручка. Поэтому сегодня пишет
-- только владелец (``author='owner'``), а ``author`` заведён с CHECK на два
-- значения, чтобы ответ автора добавлялся строкой, а не миграцией схемы.
--
-- ``delivery_status`` — на КАЖДОМ сообщении, а не на тикете: одно и то же
-- обращение может получить ответ, который ушёл письмом, и следующий, который
-- не ушёл (почту сломали между ними). Общий флаг соврал бы про один из них.
CREATE TABLE IF NOT EXISTS support_message (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    ticket_id       INTEGER NOT NULL REFERENCES support_ticket(id) ON DELETE CASCADE,
    author          TEXT    NOT NULL DEFAULT 'owner',
    body            TEXT    NOT NULL,
    delivery_status TEXT    NOT NULL DEFAULT 'pending',
    created_at      TEXT    NOT NULL DEFAULT (datetime('now')),
    CHECK (author IN ('owner', 'author'))
);

-- Разворот одного обращения: все его сообщения по возрастанию.
CREATE INDEX IF NOT EXISTS idx_support_message_ticket
    ON support_message(ticket_id, id);
