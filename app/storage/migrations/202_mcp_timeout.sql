-- 202_mcp_timeout.sql — пер-серверный таймаут вызова MCP-инструмента (F6-10).
--
-- Зачем
-- -----
-- Раньше ``app/mcp/runtime.py`` использовал ЕДИНЫЙ ``_RPC_TIMEOUT`` (60с) на
-- любой ``tools/call``. Медленные серверы (тяжёлый поиск, генерация) упирались
-- в таймаут, а быстрым 60с — слишком щедро. Эта колонка задаёт таймаут на
-- КОНКРЕТНЫЙ сервер; пустая/0/NULL → дефолт ``_RPC_TIMEOUT`` (поведение как
-- раньше, ничего не ломаем).
--
-- timeout_ms — таймаут одного ``tools/call`` в МИЛЛИСЕКУНДАХ. NULL или <=0 →
-- runtime берёт дефолт. Настраивается в /admin/mcp на каждый сервер.
--
-- Идемпотентно: раннер (app/storage/db.py) глотает "duplicate column name"
-- при повторном прогоне init_database.
ALTER TABLE mcp_server ADD COLUMN timeout_ms INTEGER;
