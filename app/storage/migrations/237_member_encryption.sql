-- Шифрование данных участников «в покое» (v2.33.x).
--
-- ЗАЧЕМ. До этой миграции содержимое участника лежало в базе открытым
-- текстом: ключи их LLM-провайдеров (``user_settings.byo_api_key_*``), токены
-- ботов, личная переписка (``dm_message.body``), черновики ИИ-ответов,
-- тексты браузерных уведомлений и факты личной памяти. Любой, у кого есть
-- ФАЙЛ базы — владелец инстанса, бэкап на диске, случайно расшаренный
-- снапшот, — читал всё это обычным SQLite-клиентом.
--
-- ЧТО ЭТА МИГРАЦИЯ ДАЁТ. Две таблицы ключей. Сами данные шифруются кодом
-- (``app/member_crypto.py``), потому что ключ живёт ВНЕ базы —
-- ``$PERSONA_DATA_DIR/member_keyring.key``. SQL не умеет шифровать, и это
-- правильно: если бы ключ был в базе, шифрование не защищало бы ровно от того,
-- от чего должно.
--
-- ЧЕГО ОНА НЕ ДАЁТ. Гарантии «владелец не увидит» нет: сервер расшифровывает
-- текст на каждом запросе, ключ лежит на том же диске. Гарантия — «файл базы
-- сам по себе бесполезен». Подробно и без прикрас: docs/MEMBER_ENCRYPTION.md.
--
-- СХЕМА КЛЮЧЕЙ (envelope, два уровня).
-- Мастер-ключ из файла не шифрует данные напрямую. Он ЗАВОРАЧИВАЕТ случайный
-- ключ записи (DEK):
--   * ``user_encryption_key``  — на пользователя: его секреты настроек, факты
--     памяти, тексты его уведомлений;
--   * ``dm_thread_key``        — на ветку переписки: тела сообщений и
--     черновики. Ключ на ВЕТКУ, а не на автора, потому что читать переписку
--     имеют право оба участника, и «ключ отправителя» превратил бы чтение
--     чужой строки в обращение к чужому ключу.
--
-- ПОЧЕМУ ON DELETE CASCADE — ЭТО ЧАСТЬ ФУНКЦИОНАЛЬНОСТИ, А НЕ ГИГИЕНА.
-- Удаление аккаунта уносит его DEK. Это крипто-шреддинг: строка, уцелевшая в
-- чьём-то старом бэкапе или в непровакуумленных страницах файла, после
-- удаления ключа не расшифровывается уже НИКЕМ, включая владельца. То же для
-- ветки переписки. FK реально срабатывают: ``PRAGMA foreign_keys = ON``
-- ставится на каждом соединении в app/storage/db.py.
--
-- LEGACY-СТРОКИ. Всё, что было записано до этой миграции, остаётся открытым
-- текстом, пока фоновый добор (``app/bootstrap/lifespan.py`` →
-- ``app.member_crypto_backfill``) не перепишет его. Отличить одно от другого
-- можно ВСЕГДА и без словаря: шифротекст начинается с маркера ``pcenc1:``.
-- Наполовину зашифрованная таблица, в которой нельзя понять, где что, — это
-- то, чего мы избегали; маркер и есть ответ.

-- ── Ключ пользователя ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS user_encryption_key (
    user_id     INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    wrapped_key BLOB    NOT NULL,
    created_at  TEXT    NOT NULL DEFAULT (datetime('now'))
);

-- ── Ключ ветки личной переписки ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS dm_thread_key (
    thread_id   INTEGER PRIMARY KEY REFERENCES dm_thread(id) ON DELETE CASCADE,
    wrapped_key BLOB    NOT NULL,
    created_at  TEXT    NOT NULL DEFAULT (datetime('now'))
);
