async def seed_builtin_skills(user_id: int) -> int:
    """Один раз на пользователя положить встроенные навыки в его список.

    Идемпотентно через kv-флаг: после первого сидинга больше не трогаем (чтобы
    не воскрешать удалённые и не перетирать выбор пользователя). Возвращает
    число реально добавленных строк.
    """
    try:
        async with get_connection() as conn:
            if (await get_kv(conn, f"{_SEED_FLAG}_{user_id}") or "").strip() == "1":
                return 0
            added = 0
            for s in BUILTIN_SKILLS:
                cur = await conn.execute(
                    "INSERT INTO skill (user_id, name, content, source_url, enabled) "
                    "VALUES (?, ?, ?, 'builtin', ?) "
                    "ON CONFLICT(user_id, name) DO NOTHING",
                    (
                        user_id,
                        str(s["name"]),
                        str(s["content"]),
                        1 if s["default_enabled"] else 0,
                    ),
                )
                added += cur.rowcount or 0
            await set_kv(conn, f"{_SEED_FLAG}_{user_id}", "1")
            await conn.commit()
        if added:
            log.info("skills.builtin.seeded", user_id=user_id, count=added)
        return added
    except Exception as exc:  # noqa: BLE001 — сидинг не должен ломать чат/настройки
        log.warning("skills.builtin.seed_failed", user_id=user_id, error=str(exc))
        return 0


