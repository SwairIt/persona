"""Первосторонняя аналитика инстанса — счётчик владельца на его же сервере.

Что это и чем НЕ является
-------------------------
Это собственный счётчик посещений и действий Persona. Он не заменяет
Яндекс.Метрику (счётчик 111901324, публичные страницы, только после согласия)
и не дублирует её: Метрика не знает наших ролей и наших таблиц, поэтому не
может ответить ни на «сколько человек дошло от лендинга до первого сообщения»,
ни на «что открывают участники, а что открываю только я».

Три модуля, три ответственности:

* :mod:`app.analytics.capture` — буфер в памяти, обезличивание, псевдонимы и
  **решение про согласие** (читать перед любой правкой сбора);
* :mod:`app.analytics.store` — весь SQL: пачечная запись, свёртка суток,
  вычистка окна, чтение агрегатов;
* :mod:`app.analytics.funnel` / :mod:`app.analytics.report` — воронка
  регистрации по существующим таблицам и сборка вьюмодели дашборда;
* :mod:`app.analytics.people` — «кто пришёл и как идёт прирост» для
  ``/root/people``. Отдельно от ``report`` намеренно: считается по
  ``users.created_at`` (то есть за всю историю инстанса, а не с даты запуска
  счётчика) и держит СВОЁ правило — чужой текст туда не попадает вовсе.

Данные не покидают этот сервер: ни одного исходящего запроса, ни одного
внешнего скрипта, ни одной сторонней куки. Рубильник — kv
``analytics_enabled`` (по умолчанию включено), окно сырых событий — kv
``analytics_retention_days`` (по умолчанию 90 суток).

Подмодули импортируются ЛЕНИВО: ``app/web/main.py`` и так стартует на пределе
бюджета холодного импорта (``tests/test_architecture_gates.py``), и тянуть SQL
и сборку отчёта в момент импорта пакета незачем — их зовут два роута.
"""

