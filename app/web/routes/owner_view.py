"""Fail-closed резолв роли для роутов member-поверхности.

Зачем отдельный модуль
----------------------
Половина изоляции в приложении держится на одной строке — ``await is_owner(uid)``:
она решает, подмешивать ли в промпт захват экрана, отдавать ли часовые карточки
в граф, писать ли настройку в ГЛОБАЛЬНЫЙ ``kv_settings`` или в личный
``user_settings``. Если этот вызов бросит исключение, у роута есть ровно два
исхода: 500 (в лучшем случае) или — если кто-то обернёт вызов «чтобы не падало»
— тихий выбор ветки по умолчанию. Ветка по умолчанию в такой развилке ДОЛЖНА
быть «участник»: показать человеку меньше, чем ему положено, — неприятно;
показать чужие данные — необратимо.

:func:`viewer_is_owner` фиксирует это правило один раз. Модули member-поверхности
импортируют её ПОД ИМЕНЕМ ``is_owner``::

    from app.web.routes.owner_view import viewer_is_owner as is_owner

— так все существующие вызовы в файле становятся fail-closed без единой правки
в местах вызова (и без риска, что новый вызов забудут обернуть).

Сегодня :func:`app.auth.owner.is_owner` и сама глушит ошибки БД внутри, так что
исключение оттуда — редкость. Это не аргумент против: инвариант «сбой резолва =
участник» не должен зависеть от того, что делает реализация двумя слоями ниже.
"""

from __future__ import annotations

from app.auth.owner import is_owner as _is_owner
from app.logging_setup import get_logger

log = get_logger("persona.owner_view")

__all__ = ["viewer_is_owner"]


async def viewer_is_owner(user_id: int | None) -> bool:
    """``True`` только если резолв ТОЧНО сказал «владелец».

    Любая ошибка (БД занята, каталог ролей недоступен, что угодно) → ``False``,
    то есть «участник»: урезанная выдача вместо чужих данных.
    """
    try:
        return await _is_owner(user_id)
    except Exception as exc:  # сбой резолва НИКОГДА не даёт доступ
        log.warning("owner_view.resolve_failed", error=str(exc))
        return False
