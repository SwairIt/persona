def _op(key: str) -> str:
    """Значение реквизита или заметная метка «не заполнено»."""
    value = (OPERATOR.get(key) or "").strip()
    if value:
        return value
    return ('<span style="background:#5a1220;color:#ffd7de;padding:0 .35em;'
            'border-radius:4px;font-weight:600">НЕ ЗАПОЛНЕНО</span>')


def operator_ready() -> bool:
    """True, когда заполнены все реквизиты, без которых нельзя брать оплату."""
    return all((OPERATOR.get(k) or "").strip() for _l, k, _h, req in _OPERATOR_FIELDS if req)


