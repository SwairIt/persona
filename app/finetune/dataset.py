def synthetic_pairs(target: int = 300, seed: int = 7) -> list[tuple[str, str]]:
    """Синтетические пары стиля: сиды + шаблонная аугментация до ``target``."""
    rng = random.Random(seed)
    pairs = list(_SEEDS)
    while len(pairs) < target:
        t = rng.choice(_TOPICS)
        up, ap = rng.choice(_TEMPLATE_PROMPTS)
        pairs.append((up.format(t=t), ap.format(t=t)))
    return pairs[:target]


def _clean(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").strip())


async def real_pairs_from_history(user_id: int, limit: int = 2000) -> list[tuple[str, str]]:
    """Реальные пары user→assistant из истории чатов пользователя.

    Берём последовательные сообщения в рамках одной сессии: user, затем
    следующий assistant. Системные сообщения и пустые пропускаем.
    """
    from app.storage.db import get_connection  # noqa: PLC0415

    out: list[tuple[str, str]] = []
    async with get_connection() as conn:
        cur = await conn.execute(
            "SELECT m.session_id, m.role, m.content FROM chat_message m "
            "JOIN chat_session s ON s.id = m.session_id "
            "WHERE s.user_id = ? AND m.is_streaming = 0 "
            "ORDER BY m.session_id, m.id",
            (user_id,),
        )
        rows = await cur.fetchall()
    pending_user: str | None = None
    pending_sess: int | None = None
    for r in rows:
        role, content, sess = r["role"], _clean(r["content"]), r["session_id"]
        if role == "user" and content:
            pending_user, pending_sess = content, sess
        elif role == "assistant" and content and pending_user and sess == pending_sess:
            if len(pending_user) >= 2 and len(content) >= 2:
                out.append((pending_user, content))
            pending_user = None
        else:
            pending_user = None
    return out[-limit:]


def _to_example(system: str, user: str, assistant: str) -> dict[str, Any]:
    return {"messages": [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
        {"role": "assistant", "content": assistant},
    ]}


def build_dataset(
    real_pairs: list[tuple[str, str]] | None = None,
    facts: list[str] | None = None,
    target_synthetic: int = 300,
    val_split: float = 0.05,
    seed: int = 7,
) -> dict[str, list[dict[str, Any]]]:
    """Собрать финальный датасет → {"train":[...], "val":[...]}.

    Дедуп по (user,assistant). Перемешивание детерминированное (seed).
    """
    system = persona_system(facts)
    seen: set[tuple[str, str]] = set()
    rows: list[dict[str, Any]] = []
    for u, a in (real_pairs or []) + synthetic_pairs(target_synthetic, seed):
        key = (_clean(u).lower(), _clean(a).lower())
        if not u or not a or key in seen:
            continue
        seen.add(key)
        rows.append(_to_example(system, _clean(u), a.strip()))
    rng = random.Random(seed)
    rng.shuffle(rows)
    n_val = max(1, int(len(rows) * val_split)) if rows else 0
    return {"train": rows[n_val:], "val": rows[:n_val]}


def write_jsonl(rows: list[dict[str, Any]], path: str | Path) -> int:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    return len(rows)


