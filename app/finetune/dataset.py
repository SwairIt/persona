"""Сборка персонального датасета для дообучения «второй копии».

Идентичность («тебя зовут Persona, ты личная копия этого человека, он твой автор
и хозяин») зашивается в системный промпт КАЖДОГО примера + отдельные обучающие
Q&A-пары (как тебя зовут / кто тебя создал / ты чей / как меня зовут). Так
дообученная модель твёрдо знает, кто она и чья, а не выдаёт себя за общий ChatGPT.

Источники:
  • синтетические пары «вопрос→ответ» в фирменном тоне Persona (FRIEND_PROMPT) —
    задают СТИЛЬ/характер (тёплый прямой друг, по-русски, можно крепко, на твоей
    стороне, честный);
  • опционально — РЕАЛЬНЫЕ пары из истории чатов пользователя (chat_message) —
    делают модель персональной именно под тебя;
  • факты из user_memory подмешиваются в системный промпт примеров (модель учится
    «помнить» тебя).

Выход — список примеров вида ``{"messages":[{role,content}...]}`` (system+user+
assistant). Пишется JSONL. Без torch/peft — только stdlib + app.storage.
"""

