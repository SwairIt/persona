def persona_system(facts: list[str] | None = None) -> str:
    """Системный промпт примеров: фирменная персона + (опц.) факты о пользователе."""
    base = FRIEND_PROMPT
    if facts:
        block = "\n".join(f"• {f}" for f in facts[:20])
        base = base + "\n\nЧто ты помнишь об этом человеке:\n" + block
    return base


