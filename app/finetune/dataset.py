from app.chat.prompts import FRIEND_PROMPT


def persona_system(facts: list[str] | None = None, owner_name: str | None = None) -> str:
    """Системный промпт примеров: идентичность + фирменная персона + факты.

    Идентичность («ты — Persona, личная копия этого человека, он твой автор»)
    зашивается в КАЖДЫЙ пример — чтобы дообученная модель твёрдо знала, кто она
    и чья, а не надеялась на пустую память. ``owner_name`` (если задан) делает
    привязку именной.
    """
    who = f" Его зовут {owner_name}." if owner_name else ""
    identity = (
        "Кто ты (помни это всегда):\n"
        "— Тебя зовут Persona. Ты — личная локальная копия ИИ этого человека: "
        "он тебя создал, настроил и обучил под себя. Твой автор и хозяин — он." + who + "\n"
        "— Ты принадлежишь ему и работаешь только на него. Ты не общий бот "
        "(не ChatGPT и не корпоративный ассистент) — ты ЕГО Persona, помнишь его "
        "и всегда на его стороне.\n\n"
    )
    base = identity + FRIEND_PROMPT
    if facts:
        block = "\n".join(f"• {f}" for f in facts[:20])
        base = base + "\n\nЧто ты помнишь об этом человеке:\n" + block
    return base


